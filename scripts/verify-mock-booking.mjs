// Reviewer-only oracle. Never import this into the booking agent or its tools.
// Deliberately projects out guest and card records from the admin response.
import { readFileSync } from "node:fs";

const [reference, expectedFile] = process.argv.slice(2);
if (reference !== '--list' && !/^CH-\d{6}$/.test(reference ?? "")) {
  console.error("Usage: node scripts/verify-mock-booking.mjs CH-123456 [expected-summary.json] | --list");
  process.exit(2);
}

try {
  const response = await fetch("http://localhost:4100/__admin/bookings", {
    signal: AbortSignal.timeout(5000),
  });
  if (!response.ok) throw new Error(`Mock verification endpoint returned ${response.status}`);
  const data = await response.json();
  const summaryOf = (booking) => ({
    reference: booking.reference,
    room: booking.room,
    rate: booking.rate,
    checkin: booking.checkin,
    checkout: booking.checkout,
    adults: booking.adults,
    breakfast: booking.breakfast,
    marketing: booking.marketing,
    total: Math.round((booking.price.total + booking.price.tax) * 100) / 100,
    payNow: booking.price.payNow,
    payAtHotel: booking.price.payAtHotel,
    termsAccepted: booking.termsAccepted,
  });
  if (reference === '--list') {
    console.log(JSON.stringify({ confirmedBookings: data.bookings.map(summaryOf) }, null, 2));
    process.exit(0);
  }
  const matches = data.bookings.filter((booking) => booking.reference === reference);
  if (matches.length !== 1) throw new Error(`Expected one confirmed booking for ${reference}; found ${matches.length}`);
  const summary = summaryOf(matches[0]);
  if (expectedFile) {
    const expected = JSON.parse(readFileSync(expectedFile, "utf8"));
    for (const [field, value] of Object.entries(expected)) {
      if (!(field in summary)) throw new Error(`Unsupported expected field: ${field}`);
      if (summary[field] !== value) throw new Error(`Booking does not match expected ${field}`);
    }
  }
  console.log(JSON.stringify({ verifiedInMockAdmin: true, summary }, null, 2));
} catch (error) {
  // Only errors generated by this verifier are relevant; never dump HTTP bodies.
  console.error(error instanceof Error ? error.message : "Mock booking verification failed");
  process.exitCode = 1;
}
